import { expect, test } from '../support'

// The console builds the only Tailwind sheet, scanning the remotes' sources. If a `@source` pattern in
// apps/crm-console/src/styles.css matches nothing, a class used only by a remote gets no CSS and the
// screen falls apart while every functional test still passes.
test('classes used only by the CS remote are generated by the console build', async ({
  signedInPage: page,
}) => {
  await expect(page.getByRole('row').nth(1)).toBeVisible()

  await expect(page.locator('[class~="min-w-[780px]"]').first()).toHaveCSS('min-width', '780px')
  await expect(page.locator('[class*="grid-cols-["]').first()).toHaveCSS('display', 'grid')
})
