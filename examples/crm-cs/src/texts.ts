/** Adds the CS texts to the console's i18n instance; call it once the instance exists. */
export function registerTexts() {
  const i18n = getI18n()
  for (const [locale, bundle] of Object.entries(texts)) {
    i18n.addResourceBundle(locale, 'translation', bundle, true, true)
  }
}
