import { useState } from 'react'
import {
  Badge,
  Input,
  Page,
  PageHeader,
  SectionHeading,
  StatCard,
  TBody,
  THead,
  Table,
  Td,
  Th,
  Tr,
} from '@crm/ui'
import { catalog } from './catalog'
import { filterCatalog } from './filter'

const PANEL = 'overflow-hidden rounded-xl border border-border-subtle bg-surface-raised'

export function App() {
  const [query, setQuery] = useState('')
  const view = filterCatalog(catalog, query)

  return (
    <Page width="lg" className="flex flex-col gap-6">
      <PageHeader
        title="Platform portal"
        description="Inventory of apps, remotes, modules, and shared packages. Generated by pnpm catalog."
      />

      <div className="flex flex-wrap gap-3">
        <StatCard label="Remotes" value={view.remotes.length} />
        <StatCard label="Modules" value={view.modules.length} />
        <StatCard label="Shared packages" value={view.packages.length} />
        <StatCard label="Owners" value={catalog.owners.length} />
      </div>

      <Input
        value={query}
        onChange={(event) => setQuery(event.target.value)}
        placeholder="Filter by name, path, or permission"
        aria-label="Filter the catalog"
        className="max-w-md"
      />

      <section className="flex flex-col gap-2">
        <SectionHeading as="h2">Remotes</SectionHeading>
        <div className={PANEL}>
          <Table>
            <THead>
              <Tr>
                <Th>Remote</Th>
                <Th>Path</Th>
                <Th>Module Federation</Th>
                <Th>Port</Th>
                <Th>Modules</Th>
              </Tr>
            </THead>
            <TBody>
              {view.remotes.map((remote) => (
                <Tr key={remote.name}>
                  <Td>{remote.name}</Td>
                  <Td className="text-ink-muted">{remote.path}</Td>
                  <Td>{remote.moduleName}</Td>
                  <Td>{remote.port}</Td>
                  <Td>{view.modules.filter((mod) => mod.remote === remote.name).length}</Td>
                </Tr>
              ))}
              {view.remotes.length === 0 ? (
                <Tr>
                  <Td colSpan={5} className="text-ink-muted">
                    No remote matches this filter.
                  </Td>
                </Tr>
              ) : null}
            </TBody>
          </Table>
        </div>
      </section>

      <section className="flex flex-col gap-2">
        <SectionHeading as="h2">Modules</SectionHeading>
        <div className={PANEL}>
          <Table>
            <THead>
              <Tr>
                <Th>Module</Th>
                <Th>Remote</Th>
                <Th>Path</Th>
                <Th>Permission</Th>
                <Th>Base path</Th>
              </Tr>
            </THead>
            <TBody>
              {view.modules.map((mod) => (
                <Tr key={`${mod.remote}:${mod.id}`}>
                  <Td>{mod.id}</Td>
                  <Td className="text-ink-muted">{mod.remote}</Td>
                  <Td>{mod.path}</Td>
                  <Td>
                    {mod.permission ? (
                      <Badge tone="info">{mod.permission}</Badge>
                    ) : (
                      <Badge tone="muted">none</Badge>
                    )}
                  </Td>
                  <Td className="text-ink-muted">{mod.basePath ?? '-'}</Td>
                </Tr>
              ))}
              {view.modules.length === 0 ? (
                <Tr>
                  <Td colSpan={5} className="text-ink-muted">
                    No module matches this filter.
                  </Td>
                </Tr>
              ) : null}
            </TBody>
          </Table>
        </div>
      </section>

      <section className="flex flex-col gap-2">
        <SectionHeading as="h2">Shared packages</SectionHeading>
        <div className={PANEL}>
          <Table>
            <THead>
              <Tr>
                <Th>Package</Th>
                <Th>Path</Th>
                <Th>Tests</Th>
                <Th>Typecheck</Th>
              </Tr>
            </THead>
            <TBody>
              {view.packages.map((pkg) => (
                <Tr key={pkg.name}>
                  <Td>{pkg.name}</Td>
                  <Td className="text-ink-muted">{pkg.path}</Td>
                  <Td>
                    <Badge tone={pkg.tests ? 'success' : 'muted'}>{pkg.tests ? 'yes' : 'no'}</Badge>
                  </Td>
                  <Td>
                    <Badge tone={pkg.typecheck ? 'success' : 'muted'}>
                      {pkg.typecheck ? 'yes' : 'no'}
                    </Badge>
                  </Td>
                </Tr>
              ))}
            </TBody>
          </Table>
        </div>
      </section>

      <footer className="flex flex-wrap items-center gap-2 text-xs text-ink-muted">
        <span>Owners:</span>
        {catalog.owners.map((owner) => (
          <Badge key={owner} tone="neutral">
            {owner}
          </Badge>
        ))}
      </footer>
    </Page>
  )
}
