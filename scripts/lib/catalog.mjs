import { existsSync, readFileSync, readdirSync } from 'node:fs'
import path from 'node:path'

const FIELD = (key) => new RegExp(`\\b${key}:\\s*'([^']+)'`)

function field(text, key) {
  return text.match(FIELD(key))?.[1] ?? null
}

function read(file) {
  return existsSync(file) ? readFileSync(file, 'utf8') : ''
}

/** Paket workspace yang punya `src/`; kandidat app, remote, dan paket bersama. */
function workspaceDirs(root) {
  const globs = read(path.join(root, 'pnpm-workspace.yaml'))
    .split('\n')
    .filter((line) => /^\s*-\s*\S+\/\*/.test(line))
    .map((line) => line.trim().replace(/^-\s*/, ''))
  return globs.flatMap((glob) => {
    const parent = glob.replace(/\/\*$/, '')
    const dir = path.join(root, parent)
    if (!existsSync(dir)) return []
    return readdirSync(dir, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => `${parent}/${entry.name}`)
      .filter((rel) => existsSync(path.join(root, rel, 'package.json')))
  })
}

function manifest(root, rel) {
  return JSON.parse(readFileSync(path.join(root, rel, 'package.json'), 'utf8'))
}

/** Remote = app dengan Module Federation `name` dan `REMOTE_PORT` di vite.config. */
function remoteOf(root, rel) {
  const config = read(path.join(root, rel, 'vite.config.ts'))
  const name = config.match(/name:\s*'([^']+)'/)?.[1] ?? null
  const port = Number(config.match(/REMOTE_PORT\s*=\s*(\d+)/)?.[1] ?? 0)
  return name && port ? { moduleName: name, port } : null
}

function modulesOf(root, rel) {
  const files = [
    path.join(root, rel, 'src', 'module.tsx'),
    path.join(root, rel, 'src', 'module.ts'),
  ]
  const modsDir = path.join(root, rel, 'src', 'modules')
  if (existsSync(modsDir)) {
    for (const entry of readdirSync(modsDir, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue
      for (const name of ['module.ts', 'module.tsx']) {
        files.push(path.join(modsDir, entry.name, name))
      }
    }
  }
  return files
    .filter((file) => existsSync(file))
    .map((file) => {
      const text = readFileSync(file, 'utf8')
      const id = field(text, 'id')
      // A remote may also export an array built from other modules (`crm-cs/src/module.tsx`); skip that.
      if (!id) return null
      const basePath = field(text, 'basePath')
      return {
        id,
        remote: manifest(root, rel).name,
        basePath,
        path: basePath?.startsWith('/remote/') ? basePath : (basePath ?? `/remote/${id}`),
        permission: field(text, 'permission'),
        labelKey: field(text, 'labelKey'),
      }
    })
    .filter(Boolean)
}

/** Owner dari `.github/CODEOWNERS`; hanya pola `*` yang dipakai sebagai default. */
function ownersOf(root) {
  const lines = read(path.join(root, '.github/CODEOWNERS')).split('\n')
  const fallback = lines
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#'))
    .find((line) => line.startsWith('* '))
  return fallback ? fallback.split(/\s+/).slice(1) : []
}

/**
 * Inventaris repo: shell, remote, modul, paket bersama, owner.
 * Dibaca dari filesystem, bukan dari daftar tetap, supaya remote/modul baru ikut terlihat.
 */
export function buildCatalog(root) {
  const apps = []
  const remotes = []
  const packages = []
  const modules = []
  for (const rel of workspaceDirs(root).sort()) {
    const pkg = manifest(root, rel)
    const isPackage = rel.startsWith('packages/')
    if (isPackage) {
      packages.push({
        name: pkg.name,
        path: rel,
        tests: Boolean(pkg.scripts?.test),
        typecheck: Boolean(pkg.scripts?.typecheck),
      })
      continue
    }
    const remote = remoteOf(root, rel)
    if (!remote) {
      if (rel.startsWith('apps/')) apps.push({ name: pkg.name, path: rel })
      continue
    }
    remotes.push({ name: pkg.name, path: rel, ...remote })
    modules.push(...modulesOf(root, rel))
  }
  return {
    schemaVersion: 1,
    apps: apps.sort((a, b) => a.path.localeCompare(b.path)),
    remotes,
    modules: modules.sort((a, b) => a.id.localeCompare(b.id)),
    packages: packages.sort((a, b) => a.name.localeCompare(b.name)),
    owners: ownersOf(root),
  }
}

/** Markdown untuk dibaca manusia; sumber kebenarannya tetap JSON. */
export function renderCatalog(catalog) {
  const lines = [
    '# Catalog',
    '',
    'Generated by `pnpm catalog`. Do not edit by hand.',
    '',
    '## Apps',
    '',
    '| App | Path |',
    '| --- | --- |',
    ...catalog.apps.map((app) => `| ${app.name} | ${app.path} |`),
    '',
    '## Remotes',
    '',
    '| Remote | Package | Module Federation name | Port |',
    '| --- | --- | --- | --- |',
    ...catalog.remotes.map(
      (remote) => `| ${remote.path} | ${remote.name} | ${remote.moduleName} | ${remote.port} |`,
    ),
    '',
    '## Modules',
    '',
    '| Module | Remote | Base path | Permission |',
    '| --- | --- | --- | --- |',
    ...catalog.modules.map(
      (mod) => `| ${mod.id} | ${mod.remote} | ${mod.path} | ${mod.permission ?? 'none'} |`,
    ),
    '',
    '## Shared packages',
    '',
    '| Package | Path | Tests | Typecheck |',
    '| --- | --- | --- | --- |',
    ...catalog.packages.map(
      (pkg) =>
        `| ${pkg.name} | ${pkg.path} | ${pkg.tests ? 'yes' : 'no'} | ${pkg.typecheck ? 'yes' : 'no'} |`,
    ),
    '',
    '## Owners',
    '',
    catalog.owners.length > 0 ? catalog.owners.map((owner) => `- ${owner}`).join('\n') : '- none',
    '',
  ]
  return lines.join('\n')
}
